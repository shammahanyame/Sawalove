create extension if not exists pgcrypto;

-- ─────────────────────────────────────────────────────────────────────────────
-- USERS: finish the shape the PHP API relied on
-- ─────────────────────────────────────────────────────────────────────────────

-- AI gateway daily caps depend on knowing who is premium.
alter table public.users add column if not exists "isPremium" boolean not null default false;

-- roles: 'user' (default), 'moderator', 'admin'. Granted ONLY by direct DB
-- change / dashboard SQL — no client-facing surface can write this column
-- (the RLS restrictive policy pins it for self-updates).
alter table public.users add column if not exists role text not null default 'user'
  check (role in ('user', 'moderator', 'admin'));

alter table public.users
  add column if not exists pin_hash text,
  add column if not exists last_active_at timestamptz not null default now();

-- Discovery / moderation query support (fixed-window "users visible & active").
create index if not exists users_visible_status_idx on public.users (visible, status);
create index if not exists users_role_idx on public.users (role);
create index if not exists users_last_active_idx on public.users (last_active_at);

-- ─────────────────────────────────────────────────────────────────────────────
-- SWIPES / MATCHES / MESSAGES / BLOCKS (chat + discovery core)
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.swipes (
  id bigint generated by default as identity primary key,
  swiper_id uuid not null references public.users(id) on delete cascade,
  target_id uuid not null references public.users(id) on delete cascade,
  action text not null check (action in ('like', 'nope', 'super_like')),
  created_at timestamptz not null default now(),
  unique (swiper_id, target_id),
  constraint swipes_no_self_swipe_check check (swiper_id <> target_id)
);
create index if not exists swipes_target_action_idx
  on public.swipes (target_id, action, created_at);
create index if not exists swipes_swiper_created_idx
  on public.swipes (swiper_id, created_at);

create table if not exists public.matches (
  id uuid primary key default gen_random_uuid(),
  user_a_id uuid not null references public.users(id) on delete cascade,
  user_b_id uuid not null references public.users(id) on delete cascade,
  -- canonical pair ordering: user_a_id < user_b_id
  unmatched_by uuid references public.users(id) on delete set null,
  unmatched_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_a_id, user_b_id),
  constraint matches_distinct_users_check check (user_a_id <> user_b_id)
);
create index if not exists matches_user_a_idx on public.matches (user_a_id, created_at);
create index if not exists matches_user_b_idx on public.matches (user_b_id, created_at);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  match_id uuid not null references public.matches(id) on delete cascade,
  sender_id uuid not null references public.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index if not exists messages_match_created_idx
  on public.messages (match_id, created_at);
create index if not exists messages_sender_idx on public.messages (sender_id);

create table if not exists public.blocks (
  id bigint generated by default as identity primary key,
  blocker_id uuid not null references public.users(id) on delete cascade,
  blocked_id uuid not null references public.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (blocker_id, blocked_id),
  constraint blocks_no_self_block_check check (blocker_id <> blocked_id)
);
create index if not exists blocks_blocked_idx on public.blocks (blocked_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- REPORTS + MODERATION
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.users(id) on delete cascade,
  reported_user_id uuid not null references public.users(id) on delete cascade,
  reason text not null check (reason in
    ('harassment', 'fake_profile', 'inappropriate_photos', 'scam', 'other')),
  details text,
  status text not null default 'pending'
    check (status in ('pending', 'upheld', 'dismissed')),
  resolved_by uuid references public.users(id) on delete set null,
  resolution_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reports_distinct_users_check check (reporter_id <> reported_user_id)
);
create index if not exists reports_status_created_idx on public.reports (status, created_at);
create index if not exists reports_reported_idx on public.reports (reported_user_id);
create index if not exists reports_reporter_idx on public.reports (reporter_id);

create table if not exists public.moderation_actions (
  id bigint generated by default as identity primary key,
  moderator_id uuid not null references public.users(id) on delete cascade,
  report_id uuid references public.reports(id) on delete set null,
  target_user_id uuid not null references public.users(id) on delete cascade,
  action text not null check (action in ('warn', 'pause', 'ban', 'reinstate', 'dismiss')),
  note text,
  created_at timestamptz not null default now()
);
create index if not exists moderation_actions_target_idx
  on public.moderation_actions (target_user_id, created_at);
create index if not exists moderation_actions_moderator_idx
  on public.moderation_actions (moderator_id, created_at);

create trigger set_reports_updated_at before update on public.reports
for each row execute function public.set_updated_at();

-- ─────────────────────────────────────────────────────────────────────────────
-- PUSH TOKENS (device FCM tokens; pruned by a scheduled housekeeping job)
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.push_tokens (
  token text primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  platform text not null default 'android' check (platform in ('android', 'ios', 'web')),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);
create index if not exists push_tokens_user_idx on public.push_tokens (user_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- RATE LIMITING: fixed-window buckets keyed like 'ip:<sha256>:<action>' or
-- 'user:<uid>:<action>'. IPs are hashed, never stored raw. The rpc_*
-- security-definer functions enforce these BEFORE performing writes, so the
-- limit holds even though clients talk to PostgREST directly.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.rate_limits (
  bucket text not null,
  window_start timestamptz not null,
  attempts integer not null default 0,
  primary key (bucket, window_start),
  constraint rate_limits_window_size_check check (window_start = date_trunc('minute', window_start))
);
create index if not exists rate_limits_window_idx on public.rate_limits (window_start);

-- ─────────────────────────────────────────────────────────────────────────────
-- AI SPEND LEDGER: one row per completed model call. The AI Edge Function
-- sums this (per day, globally and per user) BEFORE making a model request,
-- so daily caps are hard limits. Cost in whole US cents.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.ai_usage (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  endpoint text not null,
  model text not null,
  cost_usd_cents integer not null default 0 check (cost_usd_cents >= 0),
  day date not null default (now() at time zone 'utc')::date,
  created_at timestamptz not null default now()
);
create index if not exists ai_usage_day_idx on public.ai_usage (day);
create index if not exists ai_usage_user_day_idx on public.ai_usage (user_id, day);

-- ─────────────────────────────────────────────────────────────────────────────
-- APP LOG / ALERTING: structured server-side events (logins, swipes, errors,
-- moderation actions). Alert rules live in alerts.sql; this table is the
-- sink that Supabase Logs → Log Explorer / pg_cron alerts query.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.app_logs (
  id bigint generated by default as identity primary key,
  level text not null default 'info' check (level in ('debug', 'info', 'warn', 'error')),
  event text not null,
  user_id uuid references public.users(id) on delete set null,
  context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists app_logs_event_created_idx on public.app_logs (event, created_at);
create index if not exists app_logs_level_created_idx on public.app_logs (level, created_at);
create index if not exists app_logs_user_created_idx on public.app_logs (user_id, created_at);

-- Insert-only for clients; only the service role / functions can read.
alter table public.app_logs enable row level security;
create policy "Clients can append logs"
on public.app_logs
for insert
to authenticated
with check (auth.uid() = (context->>'user_id')::uuid or context->>'user_id' is null);

-- Housekeeping: single-statement maintenance functions (pg_cron friendly).
create or replace function public.housekeeping()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.rate_limits where window_start < now() - interval '2 days';
  delete from public.swipes where action = 'nope' and created_at < now() - interval '90 days';
  delete from public.push_tokens where last_seen_at < now() - interval '90 days';
  delete from public.ai_usage where day < (now() at time zone 'utc')::date - 90;
  delete from public.app_logs where created_at < now() - interval '30 days';
end;
$$;
