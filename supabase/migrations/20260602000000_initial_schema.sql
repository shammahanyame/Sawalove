-- SawaLove Supabase setup.
-- Run this in the Supabase SQL editor or with the Supabase CLI.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id uuid primary key,
  name text,
  email text,
  phone text,
  country text,
  age integer check (age is null or age between 18 and 100),
  city text default 'Douala',
  location text default 'Cameroon',
  village text default 'Cameroon',
  goal text default 'Connection',
  intent text,
  bio text default 'New to SawaLove.',
  photo text,
  visible boolean not null default false,
  status text not null default 'active'
    check (status in ('active', 'paused', 'deletion_requested', 'banned')),
  "isPremium" boolean not null default false,
  lat numeric default 0,
  lng numeric default 0,
  distance numeric default 2.5,
  preferences jsonb not null default '{}'::jsonb,
  pin_hash text,
  paused_at timestamptz,
  deletion_requested_at timestamptz,
  delete_after timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profile_photos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  slot_index integer not null check (slot_index between 0 and 5),
  storage_path text not null,
  url text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, slot_index)
);

create table if not exists public.account_deletion_requests (
  user_id uuid primary key references public.users(id) on delete cascade,
  requested_at timestamptz not null default now(),
  delete_after timestamptz not null,
  status text not null default 'pending'
    check (status in ('pending', 'cancelled', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.data_export_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  requested_at timestamptz not null default now(),
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'completed', 'failed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_users_updated_at on public.users;
create trigger set_users_updated_at
before update on public.users
for each row execute function public.set_updated_at();

