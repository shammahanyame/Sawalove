-- Alerting for SawaLove on Supabase.
--
-- app_logs (fed by RPCs + Edge Functions) is scanned every 5 minutes by
-- pg_cron jobs. Thresholds are deliberately conservative: they page on
-- spikes, not single events. Alerts land in public.alerts AND in
-- Supabase Logs → Log Explorer (query: select * from public.alerts), which
-- supports Log-based alerting webhooks in the dashboard.
--
-- DASHBOARD (one-time, can't be SQL): Logs → Alerts → create webhooks for
-- `new row in public.alerts` if you want email/Slack/Telegram delivery.

create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  rule text not null,
  severity text not null default 'warning' check (severity in ('info', 'warning', 'critical')),
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists alerts_created_idx on public.alerts (created_at);

alter table public.alerts enable row level security;

-- Read-only for staff dashboards; writes are service-role only.
create policy "Staff can read alerts"
on public.alerts
for select
to authenticated
using (public.current_role() in ('moderator', 'admin'));

-- Generic spike detector: count events of one type in a window, alert when
-- above threshold. p_dedupe_minutes suppresses repeat alerts.
create or replace function public.alert_on_spike(
  p_rule text,
  p_event text,
  p_threshold integer,
  p_window_minutes integer,
  p_severity text default 'warning',
  p_dedupe_minutes integer default 60
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  select count(*) into v_count
  from public.app_logs
  where event = p_event
    and created_at > now() - make_interval(mins => p_window_minutes);

  if v_count >= p_threshold then
    -- Dedupe: skip if the same rule fired recently.
    if not exists (
      select 1 from public.alerts
      where rule = p_rule
        and created_at > now() - make_interval(mins => p_dedupe_minutes)
    ) then
      insert into public.alerts (rule, severity, detail)
      values (p_rule, p_severity, jsonb_build_object(
        'event', p_event,
        'count', v_count,
        'window_minutes', p_window_minutes,
        'threshold', p_threshold));
    end if;
  end if;
end;
$$;

-- Rate-limit exhaustion detector (bucket key = user/ip action).
create or replace function public.alert_on_rate_limit_exhaustion(
  p_threshold integer default 50,
  p_window_minutes integer default 60
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_buckets text[];
begin
  select array_agg(distinct bucket) into v_buckets
  from public.rate_limits
  where window_start > now() - make_interval(mins => p_window_minutes)
    and attempts >= 100;

  if v_buckets is not null and array_length(v_buckets, 1) >= p_threshold then
    if not exists (
      select 1 from public.alerts
      where rule = 'rate_limit_exhaustion'
        and created_at > now() - interval '60 minutes'
    ) then
      insert into public.alerts (rule, severity, detail)
      values ('rate_limit_exhaustion', 'warning', jsonb_build_object(
        'buckets_over_100', coalesce(array_length(v_buckets, 1), 0),
        'window_minutes', p_window_minutes));
    end if;
  end if;
end;
$$;

-- Failed-signin spike (client logs these via log_event on GoTrue errors).
create or replace function public.alert_on_failed_signins(
  p_threshold integer default 100,
  p_window_minutes integer default 15
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.alert_on_spike(
    'failed_signin_spike',
    'signin_failed',
    p_threshold,
    p_window_minutes,
    'critical',
    30);
end;
$$;

-- ── Schedule (pg_cron) ──────────────────────────────────────────────────────

create extension if not exists pg_cron;

-- Every 5 minutes: error-rate + security spikes.
select cron.schedule(
  'sawalove-alerts-5min',
  '*/5 * * * *',
  $$
  select
    public.alert_on_spike('error_spike', 'edge_function_error', 20, 15, 'critical', 30),
    public.alert_on_spike('ai_budget_exhausted', 'ai_budget_exhausted', 1, 60, 'critical', 240),
    public.alert_on_spike('password_reset_spike', 'password_reset_requested', 20, 60, 'warning', 60),
    public.alert_on_rate_limit_exhaustion(50, 60),
    public.alert_on_failed_signins(100, 15);
  $$
);

-- Daily 03:00 UTC: housekeeping.
select cron.schedule(
  'sawalove-housekeeping-daily',
  '0 3 * * *',
  $$ select public.housekeeping(); $$
);
